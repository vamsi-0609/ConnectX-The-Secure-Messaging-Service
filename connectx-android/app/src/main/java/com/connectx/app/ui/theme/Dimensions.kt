package com.connectx.app.ui.theme

import androidx.compose.ui.unit.dp

/**
 * Centralized ConnectX spacing scale. Future screens should use these tokens
 * instead of inventing arbitrary padding/gap values.
 */
object ConnectXSpacing {
    val xs = 4.dp
    val sm = 8.dp
    val md = 12.dp
    val lg = 16.dp
    val xl = 24.dp
    val xxl = 32.dp

    /** Standard horizontal screen margin. */
    val screenMargin = lg
}
